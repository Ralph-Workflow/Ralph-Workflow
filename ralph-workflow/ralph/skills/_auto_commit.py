from __future__ import annotations

from typing import TYPE_CHECKING

from loguru import logger

from ralph.git.operations import stage_files
from ralph.git.scoped_auto_commit import (
    ScopedCommitResult,
    ScopedCommitStatus,
    commit_deterministic_writes,
    commit_scoped_updates,
)
from ralph.skills._agent_paths import _SKILL_ROOT_PREFIXES

if TYPE_CHECKING:
    from collections.abc import Callable, Mapping
    from pathlib import Path
    from typing import Protocol

    from ralph.git.commit_result import CommitCreationResult

    class _CreateCommitFn(Protocol):
        def __call__(
            self, repo_root: Path | str, message: str, *, expected_head: str
        ) -> CommitCreationResult: ...


SKILL_AUTO_COMMIT_SUBJECT: str = "chore(skills): sync baseline bundle"


def _extract_skill_names(dirty_paths: list[str]) -> list[str]:
    names: set[str] = set()
    for path in dirty_paths:
        for prefix in _SKILL_ROOT_PREFIXES:
            if not path.startswith(prefix):
                continue
            tail = path[len(prefix) :].strip("/")
            if not tail:
                continue
            skill_name = tail.split("/", 1)[0]
            if skill_name:
                names.add(skill_name)
            break
    return sorted(names)


def _build_body(dirty_paths: list[str]) -> str:
    body_lines = [
        "Auto-generated by Ralph skill sync",
        "",
        "Changed skills:",
    ]
    body_lines.extend(f"- {name}" for name in _extract_skill_names(dirty_paths))
    return "\n".join(body_lines)


def commit_skill_updates(
    repo_root: Path | str,
    create_commit_fn: _CreateCommitFn,
    *,
    stage_fn: Callable[[Path | str, list[str]], None] | None = None,
) -> str | None:
    if stage_fn is None:
        stage_fn = stage_files
    result = commit_scoped_updates(
        repo_root,
        scopes=tuple(sorted(_SKILL_ROOT_PREFIXES)),
        subject=SKILL_AUTO_COMMIT_SUBJECT,
        body_builder=_build_body,
        create_commit_fn=create_commit_fn,
        stage_fn=stage_fn,
    )
    if result.status is ScopedCommitStatus.CREATED:
        return result.sha
    if result.status is ScopedCommitStatus.FAILED:
        logger.debug("commit_skill_updates: failed ({}); returning None", result.error)
    return None


def commit_skill_writes(
    repo_root: Path | str,
    *,
    written_paths: list[str] | tuple[str, ...],
    pre_contents: Mapping[str, str | None],
    create_commit_fn: _CreateCommitFn,
    stage_fn: Callable[[Path | str, list[str]], None] | None = None,
    intentional_transitions: frozenset[str] | None = None,
) -> ScopedCommitResult:
    if stage_fn is None:
        stage_fn = stage_files
    return commit_deterministic_writes(
        repo_root,
        paths=tuple(written_paths),
        pre_contents=pre_contents,
        subject=SKILL_AUTO_COMMIT_SUBJECT,
        create_commit_fn=create_commit_fn,
        stage_fn=stage_fn,
        body_builder=_build_body,
        intentional_transitions=intentional_transitions,
    )


__all__ = [
    "SKILL_AUTO_COMMIT_SUBJECT",
    "ScopedCommitResult",
    "ScopedCommitStatus",
    "commit_skill_updates",
    "commit_skill_writes",
]
