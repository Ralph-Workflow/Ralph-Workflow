from __future__ import annotations

import importlib
import json
import re
import sys
from importlib.resources import files
from pathlib import Path
from typing import cast

from ralph.mcp.artifacts.format_docs import FORMAT_DOC_ARTIFACT_TYPES
from ralph.mcp.artifacts.markdown.registry import registered_specs

__all__ = ["audit_artifact_skill_types", "main"]

importlib.import_module("ralph.mcp.artifacts.markdown.specs")

UMBRELLA_SKILL_NAME = "submit-artifact"

METADATA_FILE_NAME = "metadata.json"

SKILL_FILE_GLOB = "*.md"

_FORMAT_DOC_DIR = Path(__file__).resolve().parents[1] / "mcp" / "artifacts" / "format_docs"

_FORMAT_DOC_REFERENCE_RE = re.compile(r"\.agent/artifact-formats/([A-Za-z0-9_-]+)\.md")

_ARTIFACT_TYPE_RE = re.compile(r"artifact_type\"?\s*:\s*\"?([A-Za-z0-9_]+)")

_SUBMIT_HEADING_RE = re.compile(r"^##\s+Submit\b", re.MULTILINE)

_RUNTIME_AUTHORSHIP_MARKERS = (
    "runtime-generated",
    "runtime generated",
    "runtime-written",
    "generated by the runtime",
    "written by the runtime",
    "the runtime writes",
)

_NO_SUBMIT_MARKERS = (
    "do not submit",
    "does not submit",
    "don't submit",
    "never submit",
    "must not submit",
    "shall not submit",
    "not submitted by",
    "no submission",
)

_PROHIBITION_MARKERS = (
    "do not",
    "does not",
    "don't",
    "never",
    "must not",
    "shall not",
    "not submit",
    "forbid",
    "prohibit",
)

SUBMIT_TOOL_NAME = "ralph_submit_md_artifact"


def _skill_name_for_type(artifact_type: str) -> str:
    return f"submit-{artifact_type.replace('_', '-')}-artifact"


def _expected_skill_names(artifact_types: tuple[str, ...]) -> set[str]:
    names = {UMBRELLA_SKILL_NAME}
    names.update(_skill_name_for_type(artifact_type) for artifact_type in artifact_types)
    return names


def _registered_artifact_types() -> tuple[str, ...]:
    return tuple(spec.artifact_type for spec in registered_specs())


def _format_doc_path(artifact_type: str) -> Path:
    return _FORMAT_DOC_DIR / f"{artifact_type}.md"


def _format_doc_text(artifact_type: str) -> str:
    path = _format_doc_path(artifact_type)
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return ""


def _is_reference_only(format_doc_text: str) -> bool:
    lowered = format_doc_text.lower()
    written_by_runtime = any(marker in lowered for marker in _RUNTIME_AUTHORSHIP_MARKERS)
    not_submitted_by_agents = any(marker in lowered for marker in _NO_SUBMIT_MARKERS)
    return written_by_runtime and not_submitted_by_agents


def _regex_groups(pattern: re.Pattern[str], text: str) -> list[str]:
    groups: list[str] = []
    for match in pattern.finditer(text):
        group = match.group(1)
        if isinstance(group, str):
            groups.append(group)
    return groups


def _paragraphs(text: str) -> list[str]:
    paragraphs: list[str] = []
    current: list[str] = []
    for line in text.splitlines():
        if line.strip():
            current.append(line)
            continue
        if current:
            paragraphs.append("\n".join(current))
            current = []
    if current:
        paragraphs.append("\n".join(current))
    return paragraphs


def _declares_artifact_type(text: str, artifact_type: str) -> bool:
    return artifact_type in _regex_groups(_ARTIFACT_TYPE_RE, text)


def _mentions_submit_tool_as_instruction(text: str) -> bool:
    for paragraph in _paragraphs(text):
        if SUBMIT_TOOL_NAME not in paragraph:
            continue
        lowered = paragraph.lower()
        if not any(marker in lowered for marker in _PROHIBITION_MARKERS):
            return True
    return False


def _audit_skill_text(skill_name: str, artifact_type: str, text: str) -> list[str]:
    violations: list[str] = []
    reference_only = _is_reference_only(_format_doc_text(artifact_type))

    if reference_only:
        if _ARTIFACT_TYPE_RE.search(text):
            violations.append(
                f"reference-only skill {skill_name}.md declares a submission artifact_type"
            )
        if _SUBMIT_HEADING_RE.search(text):
            violations.append(f"reference-only skill {skill_name}.md has a '## Submit' section")
        if _mentions_submit_tool_as_instruction(text):
            violations.append(
                f"reference-only skill {skill_name}.md instructs submission with {SUBMIT_TOOL_NAME}"
            )
    else:
        if not _declares_artifact_type(text, artifact_type):
            violations.append(
                f"submission skill {skill_name}.md is missing the "
                f"'artifact_type: {artifact_type}' instruction"
            )
        declared: set[str] = set(_regex_groups(_ARTIFACT_TYPE_RE, text))
        if declared and declared != {artifact_type}:
            violations.append(
                f"skill {skill_name}.md declares artifact type {sorted(declared)} but its "
                f"name derives '{artifact_type}'"
            )

    referenced_docs: set[str] = set(_regex_groups(_FORMAT_DOC_REFERENCE_RE, text))
    for referenced in sorted(referenced_docs):
        if not _format_doc_path(referenced).is_file():
            violations.append(
                f"skill {skill_name}.md references a missing format doc: {referenced}"
            )
        elif referenced != artifact_type:
            violations.append(
                f"skill {skill_name}.md references another type's format doc: {referenced} "
                f"(expected {artifact_type})"
            )
    return violations


def _audit_skill_files(content_root: Path, artifact_types: tuple[str, ...]) -> list[str]:
    violations: list[str] = []
    for artifact_type in artifact_types:
        skill_name = _skill_name_for_type(artifact_type)
        skill_path = content_root / f"{skill_name}.md"
        if not skill_path.is_file():
            continue
        try:
            text = skill_path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            violations.append(f"skill {skill_name}.md is not readable: {exc}")
            continue
        violations.extend(_audit_skill_text(skill_name, artifact_type, text))
    return violations


def _audit_metadata(content_root: Path, expected_names: set[str]) -> list[str]:
    metadata_path = content_root / METADATA_FILE_NAME
    if not metadata_path.is_file():
        return [f"missing skills metadata manifest: {METADATA_FILE_NAME}"]
    try:
        payload_raw: object = json.loads(metadata_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        return [f"skills metadata manifest is unreadable: {exc}"]
    if not isinstance(payload_raw, dict):
        return ["skills metadata manifest is not a JSON object"]
    payload = cast("dict[str, object]", payload_raw)
    listed = payload.get("skills")
    if not isinstance(listed, list):
        return ["skills metadata manifest has no 'skills' list of strings"]
    names: list[str] = []
    for item in listed:
        if not isinstance(item, str):
            return ["skills metadata manifest has no 'skills' list of strings"]
        names.append(item)

    violations: list[str] = []
    listed_names: set[str] = set(names)
    violations.extend(
        f"metadata.json skills list is missing: {name}"
        for name in sorted(expected_names - listed_names)
    )
    violations.extend(
        f"metadata.json skills list has an unknown entry: {name}"
        for name in sorted(listed_names - expected_names)
    )
    violations.extend(
        f"metadata.json skills list has a duplicate entry: {name}"
        for name in sorted({name for name in names if names.count(name) > 1})
    )
    return violations


def _resolve_content_root(root: Path | None) -> Path:
    if root is not None:
        return Path(root)
    return Path(str(files("ralph.skills") / "content"))


def audit_artifact_skill_types(root: Path | None = None) -> list[str]:
    content_root = _resolve_content_root(root)
    artifact_types = FORMAT_DOC_ARTIFACT_TYPES
    expected_names = _expected_skill_names(artifact_types)
    violations: list[str] = []

    registry_names = set(_registered_artifact_types())
    format_doc_names = set(artifact_types)
    if registry_names != format_doc_names:
        violations.append(
            "the registered artifact types and the bundled format-doc types disagree: "
            f"only registered {sorted(registry_names - format_doc_names)}, "
            f"only documented {sorted(format_doc_names - registry_names)}"
        )

    violations.extend(
        f"missing skill file: {name}.md"
        for name in sorted(expected_names)
        if not (content_root / f"{name}.md").is_file()
    )
    violations.extend(
        f"unexpected skill file: {path.name} (no registered artifact type derives it)"
        for path in sorted(content_root.glob(SKILL_FILE_GLOB))
        if path.stem not in expected_names
    )
    violations.extend(
        f"missing format doc for artifact type: {artifact_type}"
        for artifact_type in sorted(registry_names | format_doc_names)
        if not _format_doc_path(artifact_type).is_file()
    )

    violations.extend(_audit_skill_files(content_root, artifact_types))
    violations.extend(_audit_metadata(content_root, expected_names))
    return violations


def main(argv: list[str] | None = None) -> int:
    args = list(argv) if argv is not None else list(sys.argv[1:])
    if len(args) > 1:
        print(
            "Usage: python -m ralph.testing.audit_artifact_skill_types [content_root]",
            file=sys.stderr,
        )
        return 2

    content_root = _resolve_content_root(Path(args[0]) if args else None)
    if not content_root.is_dir():
        print(f"Error: skills content directory not found: {content_root}", file=sys.stderr)
        return 2

    violations = audit_artifact_skill_types(Path(args[0]) if args else None)
    if violations:
        print(f"ARTIFACT-SKILL DRIFT FOUND: {len(violations)} violation(s)")
        print("=" * 72)
        for violation in violations:
            print(f"  {violation}")
        print(
            "\nThe shipped skills must cover exactly the registered artifact types. "
            "Fix the skill files (and metadata.json), never the audit."
        )
        return 1

    print(
        "Artifact-skill audit: OK (every registered artifact type has exactly one "
        "matching skill, and metadata.json mirrors the derived set)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
